-- 1) Ficha cancelada deixa de ocupar o turno.
-- "vigente" é TRUE nas fichas válidas e NULL nas canceladas. Como NULL nunca colide numa
-- restrição UNIQUE (PostgreSQL e H2), duas fichas válidas no mesmo dia/unidade/turno continuam
-- proibidas, mas uma cancelada não impede relançar o turno.
ALTER TABLE ficha ADD COLUMN vigente BOOLEAN DEFAULT TRUE;
UPDATE ficha SET vigente = NULL WHERE situacao = 'CANCELADA';
ALTER TABLE ficha DROP CONSTRAINT uk_ficha_data_unidade_turno;
ALTER TABLE ficha ADD CONSTRAINT uk_ficha_turno_vigente UNIQUE (data, unidade_id, turno, vigente);

-- 2) Anulação de diária lançada errada (só a gestão; só se nunca entrou em um pagamento).
-- A diária sai de diaria_a_pagar e fica registrada aqui, com quem anulou e por quê.
CREATE TABLE diaria_anulacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diaria_id BIGINT NOT NULL,
    ficha_id BIGINT NOT NULL REFERENCES ficha (id),
    manobrista_id BIGINT NOT NULL REFERENCES manobrista (id),
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    data_trabalho DATE NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    reconhecedor VARCHAR(100) NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    anulado_por BIGINT NOT NULL REFERENCES usuario (id),
    anulado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX idx_diaria_anulacao_ficha ON diaria_anulacao (ficha_id);
