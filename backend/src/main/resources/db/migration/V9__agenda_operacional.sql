CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    nome VARCHAR(120) NOT NULL,
    contratante VARCHAR(120) NOT NULL,
    local VARCHAR(200) NOT NULL,
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    veiculos_previstos INTEGER NOT NULL CHECK (veiculos_previstos >= 0),
    capacidade INTEGER NOT NULL CHECK (capacidade >= 0),
    equipe_prevista INTEGER NOT NULL CHECK (equipe_prevista >= 0),
    responsavel VARCHAR(100) NOT NULL,
    valor_contratado NUMERIC(12, 2) CHECK (valor_contratado >= 0),
    despesas_previstas NUMERIC(12, 2) CHECK (despesas_previstas >= 0),
    situacao VARCHAR(16) NOT NULL CHECK (situacao IN ('PLANEJADO', 'CONFIRMADO', 'REALIZADO', 'CANCELADO')),
    observacoes VARCHAR(1000),
    CHECK (inicio < fim)
);

CREATE TABLE escala (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    evento_id BIGINT REFERENCES evento (id),
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    responsavel VARCHAR(100) NOT NULL,
    situacao VARCHAR(16) NOT NULL CHECK (situacao IN ('PLANEJADA', 'CONFIRMADA', 'REALIZADA', 'CANCELADA')),
    observacoes VARCHAR(1000),
    CHECK (inicio < fim)
);

CREATE TABLE escala_manobrista (
    escala_id BIGINT NOT NULL REFERENCES escala (id),
    manobrista_id BIGINT NOT NULL REFERENCES manobrista (id),
    PRIMARY KEY (escala_id, manobrista_id)
);

CREATE TABLE escala_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escala_id BIGINT NOT NULL REFERENCES escala (id),
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    ator_id BIGINT NOT NULL REFERENCES usuario (id),
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    situacao VARCHAR(16) NOT NULL,
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    equipe VARCHAR(5000) NOT NULL,
    evento_id BIGINT REFERENCES evento (id),
    responsavel VARCHAR(100) NOT NULL,
    observacoes VARCHAR(1000)
);

CREATE INDEX idx_evento_unidade_inicio ON evento(unidade_id, inicio);
CREATE INDEX idx_escala_unidade_inicio ON escala(unidade_id, inicio);
CREATE INDEX idx_escala_evento ON escala(evento_id);
CREATE INDEX idx_escala_manobrista ON escala_manobrista(manobrista_id, escala_id);
CREATE INDEX idx_escala_historico ON escala_historico(escala_id, id);
