CREATE TABLE auditoria_administrativa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('UNIDADE', 'USUARIO')),
    recurso_id BIGINT NOT NULL,
    ator_id BIGINT NOT NULL REFERENCES usuario(id),
    campo VARCHAR(32) NOT NULL,
    anterior TEXT,
    atual TEXT,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auditoria_adm_recurso ON auditoria_administrativa (tipo, recurso_id, id DESC);
