ALTER TABLE despesa ADD COLUMN cancelada BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE despesa_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despesa_id BIGINT NOT NULL REFERENCES despesa (id),
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    ator_id BIGINT NOT NULL REFERENCES usuario (id),
    acao VARCHAR(16) NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data DATE NOT NULL,
    categoria VARCHAR(20) NOT NULL,
    descricao VARCHAR(200) NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    justificativa VARCHAR(500)
);
CREATE INDEX idx_despesa_historico ON despesa_historico (despesa_id, id);
