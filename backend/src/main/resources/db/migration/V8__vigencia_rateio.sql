CREATE TABLE rateio_unidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    vigente_desde DATE NOT NULL,
    criado_por BIGINT NOT NULL REFERENCES usuario (id),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (unidade_id, vigente_desde)
);

CREATE TABLE rateio_unidade_socio (
    rateio_id BIGINT NOT NULL REFERENCES rateio_unidade (id),
    socio_id BIGINT NOT NULL REFERENCES socio (id),
    nome VARCHAR(100) NOT NULL,
    percentual NUMERIC(5, 2) NOT NULL CHECK (percentual > 0 AND percentual <= 100),
    PRIMARY KEY (rateio_id, socio_id)
);
CREATE INDEX idx_rateio_socio ON rateio_unidade_socio(socio_id);
