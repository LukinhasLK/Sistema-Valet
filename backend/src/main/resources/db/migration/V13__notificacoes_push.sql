CREATE TABLE notificacao_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave VARCHAR(140) NOT NULL UNIQUE,
    categoria VARCHAR(40) NOT NULL,
    destino_id BIGINT NOT NULL,
    referencia_id BIGINT,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processado_em TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_notificacao_evento_fila ON notificacao_evento (processado_em, id);

CREATE TABLE notificacao_evento_unidade (
    evento_id BIGINT NOT NULL REFERENCES notificacao_evento (id) ON DELETE CASCADE,
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    PRIMARY KEY (evento_id, unidade_id)
);

CREATE TABLE notificacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES notificacao_evento (id) ON DELETE CASCADE,
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    lida_em TIMESTAMP WITH TIME ZONE,
    UNIQUE (evento_id, usuario_id)
);
CREATE INDEX idx_notificacao_usuario ON notificacao (usuario_id, id);

CREATE TABLE notificacao_preferencia (
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    categoria VARCHAR(40) NOT NULL,
    ativa BOOLEAN NOT NULL,
    PRIMARY KEY (usuario_id, categoria)
);

CREATE TABLE push_dispositivo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    dispositivo VARCHAR(36) NOT NULL,
    endpoint VARCHAR(2048) NOT NULL UNIQUE,
    chave_publica VARCHAR(100) NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (usuario_id, dispositivo)
);

CREATE TABLE push_entrega (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notificacao_id BIGINT NOT NULL REFERENCES notificacao (id) ON DELETE CASCADE,
    dispositivo_id BIGINT REFERENCES push_dispositivo (id) ON DELETE SET NULL,
    estado VARCHAR(16) NOT NULL DEFAULT 'PENDENTE' CHECK (estado IN ('PENDENTE', 'ENVIANDO', 'ACEITA', 'FALHOU', 'EXPIRADA', 'CANCELADA')),
    tentativas INTEGER NOT NULL DEFAULT 0,
    tentar_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    codigo VARCHAR(50),
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (notificacao_id, dispositivo_id)
);
CREATE INDEX idx_push_fila ON push_entrega (estado, tentar_em, id);
