CREATE TABLE pagamento_manobrista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacao UUID NOT NULL UNIQUE,
    manobrista_id BIGINT NOT NULL REFERENCES manobrista (id),
    manobrista_nome VARCHAR(100) NOT NULL,
    valor NUMERIC(16, 2) NOT NULL CHECK (valor > 0),
    data_pagamento DATE NOT NULL,
    forma VARCHAR(20) NOT NULL CHECK (forma IN ('PIX', 'DINHEIRO', 'TRANSFERENCIA', 'OUTRA')),
    confirmado_por BIGINT NOT NULL,
    confirmador VARCHAR(100) NOT NULL,
    confirmado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    estornado_por BIGINT,
    estornador VARCHAR(100),
    estornado_em TIMESTAMP WITH TIME ZONE,
    motivo_estorno VARCHAR(500)
);

CREATE TABLE diaria_a_pagar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ficha_id BIGINT NOT NULL REFERENCES ficha (id),
    manobrista_id BIGINT NOT NULL REFERENCES manobrista (id),
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    data_trabalho DATE NOT NULL,
    custo NUMERIC(12, 2) NOT NULL CHECK (custo > 0),
    valor NUMERIC(12, 2) NOT NULL CHECK (valor > 0),
    reconhecido_por BIGINT NOT NULL,
    reconhecedor VARCHAR(100) NOT NULL,
    reconhecido_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    revisao INTEGER DEFAULT 0 NOT NULL,
    pagamento_ativo_id BIGINT REFERENCES pagamento_manobrista (id),
    UNIQUE (ficha_id, manobrista_id)
);

CREATE TABLE pagamento_manobrista_item (
    pagamento_id BIGINT NOT NULL REFERENCES pagamento_manobrista (id),
    diaria_id BIGINT NOT NULL REFERENCES diaria_a_pagar (id),
    revisao INTEGER NOT NULL,
    unidade_nome VARCHAR(100) NOT NULL,
    PRIMARY KEY (pagamento_id, diaria_id)
);

CREATE TABLE pagamento_manobrista_comprovante (
    pagamento_id BIGINT PRIMARY KEY REFERENCES pagamento_manobrista (id),
    conteudo BYTEA NOT NULL,
    sha256 VARCHAR(64) NOT NULL
);

CREATE TABLE manobrista_pix (
    manobrista_id BIGINT PRIMARY KEY REFERENCES manobrista (id) ON DELETE CASCADE,
    tipo VARCHAR(12) NOT NULL,
    chave_cifrada VARCHAR(768) NOT NULL,
    chave_mascarada VARCHAR(280) NOT NULL
);

CREATE TABLE manobrista_pix_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manobrista_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    acao VARCHAR(12) NOT NULL CHECK (acao IN ('ATUALIZOU', 'CONSULTOU')),
    tipo VARCHAR(12) NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_diaria_data ON diaria_a_pagar (data_trabalho);
CREATE INDEX idx_diaria_manobrista ON diaria_a_pagar (manobrista_id);
CREATE INDEX idx_diaria_pagamento ON diaria_a_pagar (pagamento_ativo_id);
CREATE INDEX idx_pagamento_data ON pagamento_manobrista (data_pagamento);
CREATE INDEX idx_pagamento_manobrista ON pagamento_manobrista (manobrista_id);
CREATE INDEX idx_pagamento_item_diaria ON pagamento_manobrista_item (diaria_id);
