ALTER TABLE usuario ADD COLUMN ativo BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE usuario_unidade (
    usuario_id BIGINT NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    PRIMARY KEY (usuario_id, unidade_id)
);

CREATE TABLE auditoria_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ator_id BIGINT NOT NULL REFERENCES usuario (id),
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    acao VARCHAR(30) NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auditoria_usuario_alvo ON auditoria_usuario (usuario_id, registrado_em);
CREATE INDEX idx_despesa_unidade_data ON despesa (unidade_id, data);
